"""Tiny proportional bitmap font: 5 rows tall, 3 to 5 columns wide, no antialiasing.

Glyphs are written as rows of '#'/'.'. Callers pass upper-case text; '^' and 'v' are
the up/down arrows used by the temperature row.
"""
